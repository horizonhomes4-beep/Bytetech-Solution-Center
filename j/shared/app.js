function pickMCVoice(){
  const voices=mcSpeech.voices||[];
  const english=voices.filter(v=>/^en(-|$)/i.test(String(v.lang||"")));
  const score=v=>{
    const n=String(v.name||"").toLowerCase(),l=String(v.lang||"").toLowerCase();
    let x=0;
    if(/natural|online|enhanced|neural|premium/.test(n)) x+=100;
    if(/microsoft|google|samantha|alex|daniel|karen|moira|serena|aria|guy|jenny|ryan|sonia/.test(n)) x+=35;
    if(/^en-ng$/.test(l)) x+=30;
    if(/^en-gb$/.test(l)) x+=20;
    if(/^en-us$/.test(l)) x+=15;
    if(/^en-/.test(l)) x+=5;
    return x;
  };
  return english.sort((a,b)=>score(b)-score(a))[0]||voices[0]||null;
}
