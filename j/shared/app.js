// Live question-bank utilities. All student assessments read the Firebase question bank;
// these helpers only normalise records and select a fresh random sample in memory.
function normalizeAssessmentQuestion(raw, id=""){
  if(!raw || typeof raw!=="object" || Array.isArray(raw)) return null;
  const options = raw.options && typeof raw.options === "object" && !Array.isArray(raw.options)
    ? raw.options
    : {
        A: raw.optionA ?? raw.A ?? raw.option_a,
        B: raw.optionB ?? raw.B ?? raw.option_b,
        C: raw.optionC ?? raw.C ?? raw.option_c,
        D: raw.optionD ?? raw.D ?? raw.option_d,
        E: raw.optionE ?? raw.E ?? raw.option_e
      };
  const question = raw.question ?? raw.questionText ?? raw.text ?? raw.question_text ?? "";
  const answer = raw.correctAnswer ?? raw.correct ?? raw.answer ?? raw.correctOption ?? raw.correct_option ?? "";
  const cleanOptions={};
  Object.entries(options).forEach(([k,v])=>{
    if(v!==undefined && v!==null && String(v).trim()!=="") cleanOptions[String(k).toUpperCase()]=v;
  });
  if(!String(question).trim() || !String(answer).trim() || Object.keys(cleanOptions).length<2) return null;
  let correctAnswer=String(answer).trim();
  const answerKey=correctAnswer.toUpperCase();
  if(cleanOptions[answerKey]!==undefined) correctAnswer=answerKey;
  else {
    const byText=Object.entries(cleanOptions).find(([,v])=>String(v).trim()===correctAnswer);
    if(byText) correctAnswer=byText[0];
  }
  return {...raw,id:String(raw.id||id),question:String(question),options:cleanOptions,correctAnswer};
}
function flattenAssessmentQuestions(value,prefix=""){
  const out=[];
  if(!value || typeof value!=="object") return out;
  Object.entries(value).forEach(([id,node])=>{
    if(node && typeof node==="object" && !Array.isArray(node)){
      const q=normalizeAssessmentQuestion(node,id);
      if(q) out.push(q);
      else out.push(...flattenAssessmentQuestions(node,prefix?`${prefix}/${id}`:id));
    }
  });
  return out;
}
function assessmentQuestionMatches(q,{subjectId,topicId,topicName}={}){
  if(!q) return false;
  const wantedSubject=String(subjectId||"").trim().toLowerCase();
  const qSubjects=[q.subject,q.subjectId,q.subjectKey,q.subject_id].filter(Boolean).map(x=>String(x).trim().toLowerCase());
  if(wantedSubject && !qSubjects.includes(wantedSubject)) return false;
  if(topicId==null && topicName==null) return true;
  const wantedIds=[topicId,topicName].filter(x=>x!=null && String(x).trim()!=="").map(topicKey);
  const qTopicValues=[q.topicId,q.topicIdKey,q.topic_id,q.topic,q.topicName,q.topic_name].filter(Boolean).map(topicKey);
  return wantedIds.some(w=>qTopicValues.includes(w));
}
function fisherYates(items){
  const a=[...items];
  for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}
  return a;
}
function questionFingerprint(q){
  return String(q?.question||"").replace(/<[^>]*>/g," ").replace(/\\[a-zA-Z]+|[{}$]/g," ").replace(/\s+/g," ").trim().toLowerCase();
}
async function getRecentAssessmentQuestionIds(uid,mode,scopeKey){
  if(!uid)return new Set();
  try{
    const [historySnap,attemptSnap]=await Promise.all([
      db.ref(`questionHistory/${uid}`).once("value"),
      db.ref(`studentAttempts/${uid}`).orderByChild("mode").equalTo(mode).once("value")
    ]);
    const ids=new Set(Object.keys(historySnap.val()||{}).map(String));
    const attempts=Object.values(attemptSnap.val()||{}).sort((a,b)=>Number(b.completedAt||0)-Number(a.completedAt||0));
    for(const attempt of attempts){
      if(scopeKey && attempt.scopeKey && attempt.scopeKey!==scopeKey)continue;
      for(const id of (Array.isArray(attempt.questionIds)?attempt.questionIds:[]))if(id)ids.add(String(id));
    }
    return ids;
  }catch(e){console.warn("Permanent question history could not be read; using attempt history only.",e);return new Set()}
}
async function rememberAssessmentQuestions(uid,questionIds){
  if(!uid||!Array.isArray(questionIds)||!questionIds.length)return;
  const updates={};
  [...new Set(questionIds.map(x=>String(x||"").trim()).filter(Boolean))].forEach(id=>updates[`questionHistory/${uid}/${id}`]=true);
  if(Object.keys(updates).length)await db.ref().update(updates);
}
async function selectFreshAssessmentQuestions(pool,count,{uid=null,mode="practice",scopeKey=""}={}){
  const unique=[],seenIds=new Set(),seenText=new Set();
  for(const q of (pool||[])){
    const id=String(q?.id||""),fp=questionFingerprint(q);
    if(!id||seenIds.has(id)||seenText.has(fp))continue;
    seenIds.add(id);if(fp)seenText.add(fp);unique.push(q);
  }
  const recent=await getRecentAssessmentQuestionIds(uid,mode,scopeKey);
  let available=unique.filter(q=>!recent.has(String(q.id)));
  // Recycle only after the student has genuinely exhausted this bank.
  if(available.length<count)available=unique;
  return fisherYates(available).slice(0,Math.min(count,available.length));
}
function topicKey(value){return String(value||"").toLowerCase().trim().replace(/[^a-z0-9]+/g,"-").replace(/^-+|-+$/g,"");}


// Network resilience: give students an explicit offline screen instead of leaving a
// Firebase-dependent page spinning indefinitely. The service worker caches the whole
// app shell (all student pages + assets) so the shell itself always opens offline,
// even on a fresh device that only ever loaded the app once while online.
function installMathCloudOfflineExperience(){
  if("serviceWorker" in navigator){
    navigator.serviceWorker.register("../sw.js",{scope:"../"}).then(reg=>{
      // Pick up a newer service worker automatically instead of leaving students stuck
      // on a stale cached shell after an update is published.
      reg.addEventListener("updatefound",()=>{
        const fresh=reg.installing;if(!fresh)return;
        fresh.addEventListener("statechange",()=>{
          if(fresh.state==="installed"&&navigator.serviceWorker.controller)fresh.postMessage({type:"SKIP_WAITING"});
        });
      });
      setInterval(()=>reg.update().catch(()=>{}),10*60*1000);
    }).catch(()=>{});
    let reloaded=false;
    navigator.serviceWorker.addEventListener("controllerchange",()=>{if(reloaded)return;reloaded=true;location.reload()});
  }
  let wasOffline=!navigator.onLine;
  const update=()=>{
    let banner=document.getElementById("mcNetworkBanner");
    if(!navigator.onLine){
      wasOffline=true;
      if(banner)return;
      banner=document.createElement("div");banner.id="mcNetworkBanner";banner.className="mc-offline";
      banner.innerHTML=`<div class="mc-offline-card"><img src="../assets/logo.png" alt="MathCloud Tutorial"><div class="mc-online-dot" style="justify-content:center;color:#b42318">You are offline</div><h1>No internet connection</h1><p>MathCloud needs an internet connection to load live JAMB questions, save answers and submit results. This page's shell is cached, so it stays visible while you reconnect.</p><button class="btn btn-primary" onclick="location.reload()">Try again</button></div>`;
      document.body.appendChild(banner);
    }else{
      if(banner)banner.remove();
      if(wasOffline){wasOffline=false;showNotice("You are back online.","success")}
    }
  };
  window.addEventListener("online",update);window.addEventListener("offline",update);update();
}
if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",installMathCloudOfflineExperience);else installMathCloudOfflineExperience();
