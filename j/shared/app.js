const mcMemoryCache=new Map(),mcPendingReads=new Map();
async function mcRead(path,{ttl=45000,force=false}={}){
  const key=String(path||"");if(!key)return null;
  const now=Date.now(),hit=mcMemoryCache.get(key);
  if(!force&&hit&&now-hit.time<ttl)return hit.value;
  if(!force&&mcPendingReads.has(key))return mcPendingReads.get(key);
  const promise=db.ref(key).once("value").then(snap=>{const value=snap.val();mcMemoryCache.set(key,{time:Date.now(),value});return value}).finally(()=>mcPendingReads.delete(key));
  mcPendingReads.set(key,promise);return promise;
}
function mcForgetCache(prefix=""){for(const key of [...mcMemoryCache.keys()])if(!prefix||key===prefix||key.startsWith(prefix))mcMemoryCache.delete(key)}
async function mcQueryChild(path,child,value,{ttl=45000}={}){
  const key=`query:${path}|${child}|${String(value)}`,now=Date.now(),hit=mcMemoryCache.get(key);
  if(hit&&now-hit.time<ttl)return hit.value;
  if(mcPendingReads.has(key))return mcPendingReads.get(key);
  const promise=db.ref(path).orderByChild(child).equalTo(value).once("value").then(snap=>{const value=snap.val()||{};mcMemoryCache.set(key,{time:Date.now(),value});return value}).finally(()=>mcPendingReads.delete(key));
  mcPendingReads.set(key,promise);return promise;
}

